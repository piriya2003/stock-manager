-- ── ดูข้อมูลสินค้าจาก SN ────────────────────────────────────────
-- ใช้ตอนสงสัยว่า "ทำไมหาไม่เจอในแอป" — ดูของจริงในฐานข้อมูลเลย
--
-- 🔧 แก้ SN ตรงนี้ก่อนรัน
--
-- ใช้ like '%...%' ไม่ใช่ = เพราะ SN บางตัวมีช่องว่างหรือ * ติดมาตอนสแกน
-- ถ้าเทียบแบบตรงตัวเป๊ะจะหาไม่เจอทั้งที่มีอยู่

select
  i.sn,
  i.name,
  i.status,                                              -- ต้องเป็น 'Sold' ถึงจะขึ้นในหน้ารายการที่โอน/ขายออก
  i.dispatched_at at time zone 'Asia/Bangkok' as จ่ายออกเมื่อ,   -- วันนี้คือวันที่หน้านั้นใช้กรอง
  i.dispatched_to                             as จ่ายให้,        -- ลูกค้าปลายทาง
  i.received_at  at time zone 'Asia/Bangkok'  as รับเข้าเมื่อ,
  d.do_no                                     as อยู่ในใบ         -- ว่าง = ยังไม่เคยออกใบ
from inventory i
left join do_items di  on di.sn = i.sn
left join do_headers d on d.id = di.do_header_id
where i.sn like '%202512010034%';

-- อ่านผลยังไง
--   ไม่มีแถวเลย          → SN ที่เก็บจริงไม่ตรงกับที่พิมพ์
--   status ไม่ใช่ Sold    → ยังไม่ได้ตัดสต็อก หรืออยู่ในซ่อม/เคลม
--   จ่ายออกเมื่อ ผิดวัน    → ใช้ fix-dispatched-at.sql แก้
--   จ่ายให้ ว่าง          → ไม่รู้ว่าจ่ายให้ใคร กรองตามลูกค้าจะไม่เจอ
