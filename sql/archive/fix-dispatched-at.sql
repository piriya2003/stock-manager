-- ── แก้วันที่จ่ายออกของสินค้า ──────────────────────────────────
-- ใช้ตอนของโผล่ผิดวันในหน้า "รายการสินค้าที่โอน/ขายออกไปแล้วทั้งหมด"
--
-- ทำไมถึงเพี้ยน: ก่อน 24 ส.ค. 2569 การ "เพิ่มรายการเข้าใบ DO" ที่ออกไปแล้ว
-- จะบันทึกวันที่จ่ายออกเป็นวันของใบเดิม ไม่ใช่วันที่กดเพิ่มจริง
-- ของที่เพิ่มวันนี้เลยไปโผล่ใต้วันเก่า กรองตามวันที่ทำจริงไม่เจอ
-- โค้ดแก้แล้ว แต่ของที่บันทึกผิดไปก่อนหน้านั้นต้องมาแก้ตรงนี้
--
-- 🔧 แก้ SN กับวันเวลาให้ตรงกับของจริงก่อนรัน
--    วันเวลาดูได้จากหน้า "ประวัติการเคลื่อนไหว" ในแอป
--    ต้องมี +07 ต่อท้ายเสมอ ไม่งั้นจะเพี้ยนไป 7 ชั่วโมง

update inventory
set dispatched_at = '2026-08-24 10:10:00+07'
where sn like '%202512010034%'
returning sn, name, status, dispatched_at, dispatched_to;

